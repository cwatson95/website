#!/usr/bin/env python3
"""Emit p7a_ref.js: `const REF = {...}`, the subset of refvals.json (the printed
output of derive.py) that selfTest asserts against.  Nothing here is typed by
hand: every number is copied from derive.py's output by this script.

Usage: python3 gen_ref.py [basics]   (the basics variant writes its own copy)"""
import io, json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
basics = len(sys.argv) > 1 and sys.argv[1] == 'basics'
dest = os.path.join(here, '..', 'molecule-shapes-basics') if basics else here
R = json.load(io.open(os.path.join(here, 'refvals.json'), encoding='utf-8'))

ref = {}
ref['ideal'] = R['ideal']
ref['pins'] = R['pins']
ref['prng'] = R['prng']
# equilibria: energies and the sorted angle lists (bond-bond, lone pair-bond, lone pair-lone pair)
ref['eq'] = {rho: {k: dict(E=v['E'], bb=v['bb'], lb=v['lb'], ll=v['ll'], it=v['it']) for k, v in cls.items()}
             for rho, cls in R['eq'].items()}
ref['random'] = [dict(n=r['n'], seed=r['seed'], it=r['it'], E=r['E'], U0=r['U0'][0]) for r in R['random']]
ref['named'] = R['named']
ref['approach'] = R['approach']
ref['real'] = {k: dict(distinct=v['distinct'], lpb=v['lpb'], x=v['x'], e=v['e'], geom=v['geom'], elgeom=v['elgeom'],
                       fitres=v['fitres'], model_bb=v['model_bb'], lengths=v['lengths'],
                       order=v['order'], olp=v['olp'], centre=v['centre'], outer=v['outer'])
               for k, v in R['real'].items()}
ref['real_named'] = R['real_named']
ref['compare'] = R['compare']
ref['coulomb'] = R['coulomb']
ref['ladder'] = R['ladder']
ref['ladder99'] = R['ladder99']
ref['horn'] = R['horn']
ref['names'] = R['names']
ref['curves'] = {k: R['curves'][k] for k in ('rho', 'AX2E1', 'AX2E2', 'AX3E1', 'AX4E1_ax', 'AX4E1_eq', 'AX3E2_axeq', 'AX5E1_axb')}
ref['starts'] = R['starts']
ref['gd'] = R['gd']
ref['audit'] = {rho: {k: dict(ok=v['ok']) for k, v in cls.items()} for rho, cls in R['audit']['grid'].items()}
js = ('\n/* ================================================================== *\n'
      ' *  REF: generated by build/molecule-shapes/gen_ref.py from           *\n'
      ' *  refvals.json, the printed output of derive.py -- do not edit     *\n'
      ' * ================================================================== */\n'
      'const REF=' + json.dumps(ref, separators=(',', ':')) + ';\n')
io.open(os.path.join(dest, 'p7a_ref.js'), 'w', encoding='utf-8').write(js)
print('p7a_ref.js: %d bytes -> %s' % (len(js), os.path.basename(os.path.abspath(dest))))
