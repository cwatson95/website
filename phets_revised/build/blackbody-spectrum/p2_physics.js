/* the exact SI 2019 defining constants; everything below is derived from them */
const H_PLANCK=6.62607015e-34, C_LIGHT=299792458, K_BOLTZ=1.380649e-23;
const C1=2*PI*H_PLANCK*C_LIGHT*C_LIGHT;                       /* first radiation constant 2πhc², W m² */
const C2=H_PLANCK*C_LIGHT/K_BOLTZ;                            /* second radiation constant hc/k, m K */
const SIGMA=2*Math.pow(PI,5)*Math.pow(K_BOLTZ,4)/(15*Math.pow(H_PLANCK,3)*C_LIGHT*C_LIGHT);
const PI4_15=Math.pow(PI,4)/15;                               /* ∫₀^∞ t³/(eᵗ−1) dt */
/* x = n (1 − e^−x): the peak of x^n/(eˣ−1).  Newton from x = n converges in five steps. */
function wienRoot(n){
  let x=n;
  for(let i=0;i<40;i++){ const e=Math.exp(-x), dx=(x-n*(1-e))/(1-n*e); x-=dx; if(Math.abs(dx)<1e-15*x) break; }
  return x;
}
const X5=wienRoot(5), X3=wienRoot(3);                         /* the λ-peak and the ν-peak */
const B_WIEN=C2/X5;                                           /* λ_max T, m K */
const NU_PER_T=X3*K_BOLTZ/H_PLANCK;                           /* ν_max / T, Hz/K */
/* the peak height grows as T⁵: M(λ_max) = K_PEAK T⁵, W m⁻³ K⁻⁵ — the second route to peakPow() */
const K_PEAK=2*PI*Math.pow(K_BOLTZ,5)*Math.pow(X5,5)/(Math.pow(H_PLANCK,4)*Math.pow(C_LIGHT,3)*Math.expm1(X5));

/* M_λ = π B_λ = (2πhc²/λ⁵) / (e^{hc/λkT} − 1): the spectral exitance, W m⁻² m⁻¹.
   expm1 keeps the Rayleigh–Jeans end accurate; past x = 700 the value is below 1e-280. */
function exitance(lamM,T){
  const x=C2/(lamM*T);
  if(!(x<700)) return 0;
  return C1/Math.pow(lamM,5)/Math.expm1(x);
}
/* PhET's axis unit, MW m⁻² µm⁻¹, with λ in nm: 1 W m⁻³ = 10⁻⁶ W m⁻² µm⁻¹ = 10⁻¹² MW m⁻² µm⁻¹ */
const NM=1e-9, TO_DISP=1e-12;
function specPow(lamNm,T){ return exitance(lamNm*NM,T)*TO_DISP; }
function peakNm(T){ return B_WIEN/T/NM; }
function peakPow(T){ return specPow(peakNm(T),T); }
function peakPowT5(T){ return K_PEAK*Math.pow(T,5)*TO_DISP; }
function intensity(T){ return SIGMA*T*T*T*T; }                /* σT⁴, W m⁻² */

/* ---- the fraction of σT⁴ emitted below a wavelength ------------------------------------------
   F(λT) = (15/π⁴) ∫_x^∞ t³/(eᵗ−1) dt,  x = hc/(λkT).  Two series, joined at x = 2:
   the HEAD  ∫₀^x t³/(eᵗ−1) dt = Σ a_k x^{k+3}/(k+3),  a_k = B_k/k!  (radius 2π; at x = 2 the
             40th term is 5e-21 of the first), the coefficients generated by power-series
             division of t/(eᵗ−1) = 1/Σ t^j/(j+1)! — never typed; derive.py pins them to the
             exact rationals 1/12, −1/720, 1/30240, …
   the TAIL  ∫_x^∞ t³/(eᵗ−1) dt = Σ_n e^{−nx} (x³/n + 3x²/n² + 6x/n³ + 6/n⁴)  (20 terms at x = 2). */
const X_JOIN=2, BERN_N=40;
const BERN_A=(function(){
  const inv=[1]; for(let j=1;j<=BERN_N+1;j++) inv.push(inv[j-1]/(j+1));      /* inv[j] = 1/(j+1)! */
  const a=[1];
  for(let k=1;k<=BERN_N;k++){ let s=0; for(let j=1;j<=k;j++) s+=a[k-j]*inv[j]; a.push(-s); }
  return a;
})();
function headSeries(x){
  let s=0;
  for(let k=BERN_N;k>=0;k--) s=s*x+BERN_A[k]/(k+3);
  return s*x*x*x;
}
function tailSeries(x){
  if(!(x<745)) return 0;
  const x2=x*x, x3=x2*x; let s=0;
  for(let n=1;n<=400;n++){
    const e=Math.exp(-n*x), t=e*(x3/n+3*x2/(n*n)+6*x/(n*n*n)+6/(n*n*n*n));
    s+=t; if(t<1e-18*s) break;
  }
  return s;
}
/* fraction of σT⁴ at wavelengths below lamNm, and above it — each from the branch that keeps it accurate */
function fracBelow(lamNm,T){
  if(!(lamNm>0)) return 0;
  const x=C2/(lamNm*NM*T);
  return x>=X_JOIN ? tailSeries(x)/PI4_15 : 1-headSeries(x)/PI4_15;
}
function fracAbove(lamNm,T){
  if(!(lamNm>0)) return 1;
  const x=C2/(lamNm*NM*T);
  return x>=X_JOIN ? 1-tailSeries(x)/PI4_15 : headSeries(x)/PI4_15;
}
function bandFrac(loNm,hiNm,T){ return hiNm===Infinity ? fracAbove(loNm,T) : fracBelow(hiNm,T)-fracBelow(loNm,T); }

/* ---- an independent route to the total: composite Gauss–Legendre in u = ln λ --------------------
   ∫₀^∞ M_λ dλ = ∫ M_λ λ du over λ_max/60 … 10⁶ λ_max (what lies outside is below 1e-17 of σT⁴) */
function glRule(n){
  const x=[], w=[];
  for(let i=1;i<=n;i++){
    let z=Math.cos(PI*(i-0.25)/(n+0.5)), dp=0;
    for(let it=0;it<100;it++){
      let p0=1, p1=z;
      for(let k=2;k<=n;k++){ const p2=((2*k-1)*z*p1-(k-1)*p0)/k; p0=p1; p1=p2; }
      dp=n*(z*p1-p0)/(z*z-1);
      const dz=p1/dp; z-=dz; if(Math.abs(dz)<1e-16) break;
    }
    x.push(z); w.push(2/((1-z*z)*dp*dp));
  }
  return {x,w};
}
const GL16=glRule(16);
function quadGL(f,a,b,panels){
  const h2=(b-a)/panels; let s=0;
  for(let p=0;p<panels;p++){
    const m=a+(p+0.5)*h2, r=h2/2;
    for(let i=0;i<GL16.x.length;i++) s+=GL16.w[i]*f(m+r*GL16.x[i]);
  }
  return s*h2/2;
}
function totalByQuadrature(T){
  const lm=B_WIEN/T;
  return quadGL(u=>{ const L=Math.exp(u); return exitance(L,T)*L; },Math.log(lm/60),Math.log(lm*1e6),64);
}

/* ---- the classical laws that came before Planck ---------------------------------------------- */
function rjExitance(lamM,T){ return 2*PI*C_LIGHT*K_BOLTZ*T/Math.pow(lamM,4); }        /* Rayleigh–Jeans */
function wienExitance(lamM,T){ return C1/Math.pow(lamM,5)*Math.exp(-C2/(lamM*T)); }   /* Wien 1896 */
function rjRatio(x){ return Math.expm1(x)/x; }                  /* M_RJ / M_Planck */
function wienRatio(x){ return -Math.expm1(-x); }                /* M_Wien / M_Planck */
function xOf(lamNm,T){ return C2/(lamNm*NM*T); }

/* ---- colorimetry: the CIE 1931 2° observer, the CIE's own table (p2_cie.js) -------------------- */
const CIE_STEP=5;                                            /* nm between the embedded rows */
function bbXYZ(T){
  let X=0,Y=0,Z=0;
  for(const r of CIE1931){ const m=exitance(r[0]*NM,T); X+=m*r[1]; Y+=m*r[2]; Z+=m*r[3]; }
  const d=CIE_STEP*NM;
  return [X*d,Y*d,Z*d];
}
function chroma(T){ const c=bbXYZ(T), s=c[0]+c[1]+c[2]; return [c[0]/s,c[1]/s]; }
/* sRGB (IEC 61966-2-1) primaries, D65 — the matrix and transfer curve of diffraction.html */
const SRGB_M=[[ 3.2406,-1.5372,-0.4986],
              [-0.9689, 1.8758, 0.0415],
              [ 0.0557,-0.2040, 1.0570]];
function srgbGamma(u){
  u=clamp(u,0,1);
  return u<=0.0031308 ? 12.92*u : 1.055*Math.pow(u,1/2.4)-0.055;
}
function xyzToLin(X,Y,Z){
  return [SRGB_M[0][0]*X+SRGB_M[0][1]*Y+SRGB_M[0][2]*Z,
          SRGB_M[1][0]*X+SRGB_M[1][1]*Y+SRGB_M[1][2]*Z,
          SRGB_M[2][0]*X+SRGB_M[2][1]*Y+SRGB_M[2][2]*Z];
}
/* the body's colour: chromaticity only (Y set to 1), negative channels clipped (out of gamut),
   normalised to the brightest channel; linear light */
function bbLinear(T){
  const c=bbXYZ(T);
  if(!(c[1]>0)) return [0,0,0];
  const v=xyzToLin(c[0]/c[1],1,c[2]/c[1]).map(u=>Math.max(u,0)), m=Math.max(v[0],v[1],v[2]);
  return m>0 ? v.map(u=>u/m) : [0,0,0];
}
function bbBytes(T){ return bbLinear(T).map(u=>Math.round(255*srgbGamma(u))); }
/* luminous efficacy of the radiation, 683 lm/W × ∫M ȳ dλ / σT⁴ (683 lm/W: the SI candela) */
const K_CD=683;
function efficacy(T){ return K_CD*bbXYZ(T)[1]/intensity(T); }
/* display only: the glow's brightness, log-compressed luminance relative to 6500 K */
let Y6500=0;
function glowLevel(T){
  if(!Y6500) Y6500=bbXYZ(6500)[1];
  const r=bbXYZ(T)[1]/Y6500;
  return r>0 ? clamp(1+Math.log10(r)/12,0,1) : 0;
}
/* a monochromatic line's colour, interpolated in the 5-nm table, desaturated toward white and
   normalised to its brightest channel.  Takes NANOMETRES; outside 360–830 nm it is black. */
function cmfAt(nm){
  if(!(nm>=360&&nm<=830)) return null;
  const f=(nm-360)/CIE_STEP, i=Math.min(CIE1931.length-2,Math.floor(f)), t=f-i, a=CIE1931[i], b=CIE1931[i+1];
  return [a[1]+(b[1]-a[1])*t, a[2]+(b[2]-a[2])*t, a[3]+(b[3]-a[3])*t];
}
function monoLinear(nm){
  const c=cmfAt(nm);
  if(!c) return [0,0,0];
  let v=xyzToLin(c[0],c[1],c[2]);
  const lo=Math.min(v[0],v[1],v[2]);
  if(lo<0) v=v.map(u=>u-lo);
  const m=Math.max(v[0],v[1],v[2]);
  return m>0 ? v.map(u=>u/m) : [0,0,0];
}
/* the band fades where the eye does (display only): sqrt(min(1, 4 ȳ)) */
function monoLevel(nm){ const c=cmfAt(nm); return c ? Math.sqrt(Math.min(1,4*c[1])) : 0; }
function cssOfLinear(v,k){ const s=k===undefined?1:k;
  return 'rgb('+Math.round(255*srgbGamma(v[0]*s))+','+Math.round(255*srgbGamma(v[1]*s))+','+Math.round(255*srgbGamma(v[2]*s))+')'; }
function hexOfBytes(b){ return '#'+b.map(u=>('0'+u.toString(16)).slice(-2)).join(''); }

/* ---- PhET's photometer and star (PhET's values, reproduced exactly) --------------------------
   each channel = floor(255 · min(1, r) · M(λ_c)/max(M(650), M(550), M(450))),  r = 0.02 √(T − 798 K);
   the halo: radius 5 + 47.5 r px, opacity 0.3 r.  798 K is the Draper point. */
const PH_LAM=[650,550,450];                                  /* R, G, B sample wavelengths, nm */
const PH_DRAPER=798, PH_RAMP=0.02;
function phRenorm(T){ return PH_RAMP*Math.sqrt(Math.max(T,PH_DRAPER)-PH_DRAPER); }
function photometerRaw(T){
  const s=PH_LAM.map(l=>specPow(l,T)), r=Math.max(s[0],s[1],s[2]), a=Math.min(phRenorm(T),1);
  return s.map(v=>r>0 ? 255*a*v/r : 0);
}
function photometer(T){ return photometerRaw(T).map(Math.floor); }
function haloRadius(T){ return 5+47.5*phRenorm(T); }
function haloAlpha(T){ return 0.3*phRenorm(T); }

/* ---- PhET's ranges, presets, zoom ladders and bands (PhET's values) ---------------------------- */
const T_MIN=200, T_MAX=11000, T_SNAP=50, T_DEFAULT=5800;
const PRESETS=[{id:'earth',name:'Earth',T:250},{id:'bulb',name:'Light Bulb',T:3000},
               {id:'sun',name:'Sun',T:5800},{id:'sirius',name:'Sirius A',T:9950}];
function presetAt(T){ return PRESETS.find(p=>p.T===T)||null; }
function snapT(T){ return clamp(Math.round(T/T_SNAP)*T_SNAP,T_MIN,T_MAX); }
const ZOOM_X=[750,1500,3000,6000,12000,24000,48000];         /* wavelength axis maximum, nm (×2) */
const ZOOM_Y=[]; for(let k=-10;k<=2;k++) ZOOM_Y.push(100*Math.pow(5,k));   /* power axis maximum, MW/m²/µm (×5) */
const IX_DEFAULT=2, IY_DEFAULT=10;                            /* 3 µm and 100 MW/m²/µm */
const BANDS=[{id:'xray',name:'X-Ray',short:'X',lo:0,hi:10},{id:'uv',name:'Ultraviolet',short:'UV',lo:10,hi:380},
             {id:'vis',name:'Visible',short:'vis',lo:380,hi:780},{id:'ir',name:'Infrared',short:'IR',lo:780,hi:1e5},
             {id:'far',name:'beyond 100 µm',short:'>100 µm',lo:1e5,hi:Infinity}];
const MAX_SAVED=2;
/* the smallest axis maxima that frame a curve: λ-axis ≥ 5 λ_max, power axis ≥ the peak */
function fitZoom(T){
  const lx=5*peakNm(T), py=peakPow(T);
  let ix=ZOOM_X.findIndex(z=>z>=lx); if(ix<0) ix=ZOOM_X.length-1;
  let iy=ZOOM_Y.findIndex(z=>z>=py); if(iy<0) iy=ZOOM_Y.length-1;
  return [ix,iy];
}
