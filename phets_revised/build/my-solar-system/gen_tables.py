#!/usr/bin/env python3
"""gen_tables.py -- turn derive.py's REFJSON line into p2_ref_mss.js, the table
selfTest pins against.  No number is typed by hand."""
import io
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
txt = io.open(os.path.join(here, 'refvals.txt'), encoding='utf-8').read()
i = txt.rindex('REFJSON ')
REF = json.loads(txt[i + len('REFJSON '):])
for k in ('units', 'presets', 'orders', 'twobody', 'conserve', 'facts', 'runs', 'merge', 'radius'):
    assert REF.get(k), (k, sorted(REF))
js = ('\n/* ================================================================== *\n'
      ' *  REF -- every reference value selfTest pins against, generated by   *\n'
      " *  gen_tables.py from build/my-solar-system/refvals.txt (derive.py's  *\n"
      ' *  output: scipy solve_ivp at rtol 1e-12, and its own PEFRL twin).    *\n'
      ' * ================================================================== */\n'
      'const REF = ' + json.dumps(REF, sort_keys=True, separators=(',', ':')) + ';\n')
io.open(os.path.join(here, 'p2_ref_mss.js'), 'w', encoding='utf-8').write(js)
print('p2_ref_mss.js: %d bytes, %d top-level keys' % (len(js), len(REF)))
