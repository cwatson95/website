#!/usr/bin/env python3
"""Emit p2_data.js — every table the sim carries, straight out of the sources.

  SYMBOL[Z], ENAME[Z]   PhET's SHRED symbol table and its English element-name
                        strings (inventory.json, decoded from the same build)
  STABLE[Z]             PhET's stableElementTable: the neutron numbers that
                        give a nuclide PhET calls stable
  MOSTN[Z]              PhET's numNeutronsInMostCommonIsotope
  SMASS[Z]              PhET's standardMassTable (standard atomic weights)
  ISOT[Z][A]            PhET's isotope table: [atomic mass / u, abundance]
  PTXY[Z]               the periodic-table cell (column, row), derived from
                        group/period and checked against periodic_table.html
  DEXC                  mass excess / keV for every nuclide the chart view
                        draws, from NUBASE via this repo's periodic_table.html

Nothing in the output is typed by hand.
"""
import io
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "_out")
INV = os.path.normpath(os.path.join(HERE, "..", "_survey", "inventory.json"))
PT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "..",
                                   "projects", "simulations", "periodic_table.html"))

P = json.load(io.open(os.path.join(OUT, "phet_tables.json"), encoding="utf-8"))
INVD = json.load(io.open(INV, encoding="utf-8"))["build-an-atom"]["ui_by_repo"]["SHRED"]

s = io.open(PT, encoding="utf-8").read()
ISO = {int(k): v for k, v in
       json.loads(re.search(r"const ISO=(\{.*?\});\s*\n", s, re.S).group(1)).items()}
EL = json.loads(re.sub(r",\s*\]", "]",
                       s[s.index("const EL=[") + len("const EL="):s.index("\n];", s.index("const EL=[")) + 2]))

SYM = P["symbols"]
STABLE = P["stable"]

# English names: PhET's own localized strings, keyed by the non-localized name
names = [""]
for z in range(1, 119):
    key = P["names"][z]
    nm = INVD.get(key)
    if nm is None:                      # PhET's non-localized list spells Cn wrong
        nm = {r[0]: r[2] for r in EL}[z]
    names.append(nm)

lay = {}
for r in EL:
    z, group, period = r[0], r[3], r[4]
    if 57 <= z <= 71:
        lay[z] = (3 + z - 57, 9)
    elif 89 <= z <= 103:
        lay[z] = (3 + z - 89, 10)
    else:
        lay[z] = (group, period)

# mass excesses: every PhET-stable nuclide, plus the landmarks the views name
EXTRA = [(1, 3), (2, 6), (3, 8), (4, 7), (4, 10), (5, 12), (6, 14), (7, 16), (8, 19),
         (9, 18), (10, 23), (19, 40), (26, 56), (26, 58), (28, 62), (28, 64), (43, 98),
         (61, 145), (83, 209), (90, 232), (92, 235), (92, 238), (94, 239)]
want = sorted(set([(z, z + n) for z, ns in enumerate(STABLE) for n in ns] + EXTRA))
exc = []
for z, a in want:
    row = [r for r in ISO.get(z, []) if r[0] == a]
    if row:
        exc.append([z, a, int(round(row[0][1]))])
# every stable nuclide must have a mass excess, or the binding curve has holes
missing = [(z, a) for z, a in want if not any(e[0] == z and e[1] == a for e in exc)]
assert not missing, missing


def jnum(x):
    return repr(x) if not isinstance(x, float) else ("%.12g" % x)


out = []
out.append("""
/* ================================================================== *
 *  data tables                                                        *
 *                                                                     *
 *  SYMBOL / ENAME / STABLE / MOSTN / SMASS / ISOT are PhET's own,      *
 *  read out of the minified build-an-atom_en.html 1.9.3 by            *
 *  build/build-an-atom/extract_phet.py -- SHRED's AtomIdentifier       *
 *  tables and its English element-name strings.  PTXY is the standard  *
 *  18-column periodic-table layout, derived from group and period and  *
 *  checked cell by cell against this repo's periodic_table.html.       *
 *  DEXC is the mass excess in keV of every nuclide the chart view      *
 *  draws, from NUBASE by way of periodic_table.html -- an INDEPENDENT  *
 *  table, which is what makes the cross-checks in selfTest worth        *
 *  anything.  Generated by gen_data.py; nothing here is typed.         *
 * ================================================================== */""")
out.append("const SYMBOL=%s;" % json.dumps(SYM))
out.append("const ENAME=%s;" % json.dumps(names))
out.append("const STABLE=%s;" % json.dumps(STABLE))
out.append("const MOSTN=%s;" % json.dumps(P["mostCommonN"]))
out.append("const SMASS=%s;" % json.dumps(P["standardMass"]))
iso = {}
for z, d in P["isotopes"].items():
    iso[int(z)] = {int(a): [v["atomicMass"], v["abundance"]] for a, v in d.items()}
out.append("const ISOT=%s;" % json.dumps({str(k): {str(a): v for a, v in sorted(d.items())}
                                          for k, d in sorted(iso.items())}))
out.append("const PTXY=[null%s];" % "".join(",[%d,%d]" % lay[z] for z in range(1, 119)))
out.append("/* PhET's atomic radii / pm (AtomIdentifier.getAtomicRadius) — the only\n"
           "   length in the file, used to say how far from scale the picture is */")
rad = P["radius"]
out.append("const ARAD=[0%s];" % "".join(
    ",%s" % (rad.get(str(z)) if rad.get(str(z)) is not None else "null") for z in range(1, 119)))
out.append("/* [Z, A, mass excess / keV] */")
out.append("const DEXC=%s;" % json.dumps(exc))
out.append("""/* PhET's four AtomValuePool lists: the (protons, neutrons, electrons) the
   game may pose.  Levels 1 and 2 share the 32-atom list, levels 3 and 4 the
   60-atom one. */""")
pools = json.load(io.open(os.path.join(OUT, "phet_pools.json"), encoding="utf-8"))
out.append("const GAME_POOLS=%s;" % json.dumps(pools))

body = "\n".join(out) + "\n"
io.open(os.path.join(HERE, "p2_data.js"), "w", encoding="utf-8").write(body)
print("p2_data.js  %d lines, %.1f KB" % (len(body.splitlines()), len(body.encode()) / 1024))
print("  %d symbols, %d names, %d stable rows, %d isotope elements, %d mass excesses"
      % (len(SYM), len(names), len(STABLE), len(iso), len(exc)))
print("  name at Z=112: %r (PhET's non-localized list says %r)" % (names[112], P["names"][112]))
