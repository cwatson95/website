#!/usr/bin/env python3
"""Copy derive.py's printed output into the two generated part files.

  p2a_data.js  the real-molecule table (PhET's, extracted from its build) and
               the measured dipole moments (NIST CCCBDB) -- data the sim draws
  p7a_ref.js   REF, every reference value selfTest asserts against

Run derive.py first (it writes refvals.json)."""
import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REF = json.load(io.open(os.path.join(HERE, 'refvals.json'), encoding='utf-8'))

ORDER = ['H2', 'N2', 'O2', 'F2', 'HF', 'H2O', 'CO2', 'HCN', 'O3', 'NH3', 'BH3', 'BF3',
         'CH2O', 'CH4', 'CH3F', 'CH2F2', 'CHF3', 'CHCl3', 'CF4']

data = {
    'order': ORDER,
    'mol': REF['realTable'],
    'measured': REF['measured'],
    'anglesKnown': REF['realAnglesKnown'],
}
js = ['\n/* ================================================================== *',
      ' *  generated by build/molecule-polarity/gen_ref.py -- do not edit     *',
      ' *  MOLDATA: PhET Molecule Polarity 2.0.2\'s own real-molecule table,   *',
      ' *  extracted from its build: geometry (PubChem, angstrom, the origin  *',
      ' *  shifted to PhET\'s own origin atom), bonds, Hirshfeld partial       *',
      ' *  charges (ORCA) and the molecular dipole (Psi4, debye).             *',
      ' *  MEASURED: NIST CCCBDB "Experimental Dipole Moments"                *',
      ' *  (cccbdb.nist.gov/diplistx.asp, retrieved 2026-09-22), debye to the *',
      ' *  three decimals it prints, with CCCBDB\'s own source code.  Borane   *',
      ' *  is absent from that table and carries no entry.                    *',
      ' *  ANGLES_KNOWN: CCCBDB "Experimental bond angles" (release 22, May   *',
      ' *  2022) where measured, or the point group where "symmetry".         *',
      ' * ================================================================== */',
      'const MOLDATA=' + json.dumps(data['mol'], separators=(',', ':')) + ';',
      'const MOLORDER=' + json.dumps(ORDER, separators=(',', ':')) + ';',
      'const MEASURED=' + json.dumps(data['measured'], separators=(',', ':')) + ';',
      'const ANGLES_KNOWN=' + json.dumps(data['anglesKnown'], separators=(',', ':')) + ';',
      '']
io.open(os.path.join(HERE, 'p2a_data.js'), 'w', encoding='utf-8').write('\n'.join(js))

ref = ['\n/* ================================================================== *',
       ' *  REF -- generated by build/molecule-polarity/gen_ref.py from        *',
       ' *  derive.py\'s refvals.json.  Every "(python)" assertion in selfTest  *',
       ' *  reads a value from here; nothing in this block is hand-typed.      *',
       ' * ================================================================== */',
       'const REF=' + json.dumps(REF, separators=(',', ':')) + ';',
       '']
io.open(os.path.join(HERE, 'p7a_ref.js'), 'w', encoding='utf-8').write('\n'.join(ref))
print('p2a_data.js %d bytes, p7a_ref.js %d bytes'
      % (os.path.getsize(os.path.join(HERE, 'p2a_data.js')),
         os.path.getsize(os.path.join(HERE, 'p7a_ref.js'))))
