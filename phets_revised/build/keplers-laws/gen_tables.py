#!/usr/bin/env python3
"""gen_tables.py -- turn derive.py's REFJSON line into p2_ref_kl.js, the table
selfTest pins against.  No number is typed by hand: every value in REF was
printed by the arithmetic in derive.py."""
import io
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
txt = io.open(os.path.join(here, 'refvals.txt'), encoding='utf-8').read()
i = txt.rindex('REFJSON ')
REF = json.loads(txt[i + len('REFJSON '):])
assert REF['kepler'] and REF['els'] and REF['sectors'] and REF['targets'], sorted(REF)
js = ('\n/* ================================================================== *\n'
      ' *  REF -- every reference value selfTest pins against, generated by   *\n'
      " *  gen_tables.py from build/keplers-laws/refvals.txt (derive.py's     *\n"
      ' *  output: scipy brentq, quad and solve_ivp at rtol 1e-13).           *\n'
      ' * ================================================================== */\n'
      'const REF = ' + json.dumps(REF, sort_keys=True, separators=(',', ':')) + ';\n')
io.open(os.path.join(here, 'p2_ref_kl.js'), 'w', encoding='utf-8').write(js)
print('p2_ref_kl.js: %d bytes, %d top-level keys' % (len(js), len(REF)))
