#!/usr/bin/env python3
"""gen_tables.py -- turn derive.py's REFJSON line into p2_ref_go.js, the table
selfTest pins against.  No number is typed by hand."""
import io
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
txt = io.open(os.path.join(here, 'refvals.txt'), encoding='utf-8').read()
i = txt.rindex('REFJSON ')
REF = json.loads(txt[i + len('REFJSON '):])
for k in ('phet', 'meas', 'cmp', 'scenes', 'circ', 'third', 'two', 'runs', 'cons', 'coast',
          'orders', 'shadow', 'modelmoon', 'sizes', 'px', 'window', 'periods', 'sweep',
          'mass', 'vsmeas', 'kepler_resid'):
    assert REF.get(k) is not None, (k, sorted(REF))
js = ('\n/* ================================================================== *\n'
      ' *  REF -- every reference value selfTest pins against, generated by   *\n'
      " *  gen_tables.py from build/gravity-and-orbits/refvals.txt            *\n"
      " *  (derive.py: scipy brentq, solve_ivp DOP853 at rtol 1e-13, and its  *\n"
      ' *  own PEFRL twin).                                                   *\n'
      ' * ================================================================== */\n'
      'const REF = ' + json.dumps(REF, sort_keys=True, separators=(',', ':')) + ';\n')
io.open(os.path.join(here, 'p2_ref_go.js'), 'w', encoding='utf-8').write(js)
print('p2_ref_go.js: %d bytes, %d top-level keys' % (len(js), len(REF)))
