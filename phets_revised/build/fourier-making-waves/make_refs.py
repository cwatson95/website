#!/usr/bin/env python3
"""Turn derive.py's refvals.txt into p7_refs.js, so selfTest asserts against
the PRINTED output of the Python twin and no reference value is ever retyped."""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
src = io.open(os.path.join(HERE, 'refvals.txt'), encoding='utf-8').read()
out, names = [], []
for line in src.splitlines():
    m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*)\s{2,}(\[[^\]]*\]|[-\d.eE+]+|true|false)\s*(?:#\s*(.*))?$', line)
    if not m:
        continue
    name, val, note = m.group(1), m.group(2), (m.group(3) or '').strip()
    names.append(name)
    out.append('  %s: %s,%s' % (name, val, ('   /* ' + note + ' */') if note else ''))
assert len(names) == len(set(names)), 'duplicate reference name'
assert len(names) > 50, len(names)
body = ('\n/* ================================================================== *\n'
        ' *  reference values — the printed output of derive.py, read in full   *\n'
        ' *  (build/fourier-making-waves/refvals.txt).  Generated by            *\n'
        ' *  make_refs.py; never edited by hand.                                *\n'
        ' * ================================================================== */\n'
        'const REF={\n' + '\n'.join(out) + '\n};\n')
io.open(os.path.join(HERE, 'p7_refs.js'), 'w', encoding='utf-8').write(body)
print('p7_refs.js: %d reference values' % len(names))
