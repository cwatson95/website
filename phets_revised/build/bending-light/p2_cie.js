const CIE_STEP=5;   /* nm between the embedded rows */
/* sRGB (IEC 61966-2-1) primaries, D65 — the matrix and transfer curve of diffraction.html */
const SRGB_M=[[ 3.2406,-1.5372,-0.4986],
              [-0.9689, 1.8758, 0.0415],
              [ 0.0557,-0.2040, 1.0570]];
function srgbGamma(u){
  u=clamp(u,0,1);
  return u<=0.0031308 ? 12.92*u : 1.055*Math.pow(u,1/2.4)-0.055;
}
function xyzToLin(X,Y,Z){
  return [SRGB_M[0][0]*X+SRGB_M[0][1]*Y+SRGB_M[0][2]*Z,
          SRGB_M[1][0]*X+SRGB_M[1][1]*Y+SRGB_M[1][2]*Z,
          SRGB_M[2][0]*X+SRGB_M[2][1]*Y+SRGB_M[2][2]*Z];
}
/* a monochromatic line's colour, interpolated in the 5-nm table, desaturated toward white and
   normalised to its brightest channel.  Takes NANOMETRES; outside 360–830 nm it is black. */
function cmfAt(nm){
  if(!(nm>=360&&nm<=830)) return null;
  const f=(nm-360)/CIE_STEP, i=Math.min(CIE1931.length-2,Math.floor(f)), t=f-i, a=CIE1931[i], b=CIE1931[i+1];
  return [a[1]+(b[1]-a[1])*t, a[2]+(b[2]-a[2])*t, a[3]+(b[3]-a[3])*t];
}
function monoLinear(nm){
  const c=cmfAt(nm);
  if(!c) return [0,0,0];
  let v=xyzToLin(c[0],c[1],c[2]);
  const lo=Math.min(v[0],v[1],v[2]);
  if(lo<0) v=v.map(u=>u-lo);
  const m=Math.max(v[0],v[1],v[2]);
  return m>0 ? v.map(u=>u/m) : [0,0,0];
}
/* the band fades where the eye does (display only): sqrt(min(1, 4 ȳ)) */
function monoLevel(nm){ const c=cmfAt(nm); return c ? Math.sqrt(Math.min(1,4*c[1])) : 0; }
function cssOfLinear(v,k){ const s=k===undefined?1:k;
  return 'rgb('+Math.round(255*srgbGamma(v[0]*s))+','+Math.round(255*srgbGamma(v[1]*s))+','+Math.round(255*srgbGamma(v[2]*s))+')'; }
