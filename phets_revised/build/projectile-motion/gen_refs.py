#!/usr/bin/env python3
"""refvals.txt (derive.py's printed output) -> p7a_refs.js, the REF table the
selfTest reads through R('<label>').  Every value goes in as the literal derive
printed; nothing is retyped (Known-bad: hand-transcribed tables fail silently).
A label printed twice is an error, not a silent overwrite."""
import io, os, re, json
here = os.path.dirname(os.path.abspath(__file__))
ref = {}
for line in io.open(os.path.join(here, 'refvals.txt'), encoding='utf-8'):
    line = line.rstrip('\n')
    if line.startswith('===') or not line.strip():
        continue
    m = re.match(r'^(.*?)\s{2,}(\S+)\s*$', line)
    if not m:
        continue
    key, tok = m.group(1).strip(), m.group(2)
    if tok == 'None':
        val = None
    else:
        try:
            val = float(tok)
        except ValueError:
            continue
    if key in ref:
        raise SystemExit('duplicate label in refvals.txt: %r' % key)
    ref[key] = val
body = ',\n'.join('  %s:%s' % (json.dumps(k), 'null' if v is None else repr(v)) for k, v in ref.items())
js = ('\n/* REF: the printed output of build/projectile-motion/derive.py (refvals.txt),\n'
      '   generated by gen_refs.py; read through R(label) in selfTest */\n'
      'const REF={\n' + body + '\n};\n')
io.open(os.path.join(here, 'p7a_refs.js'), 'w', encoding='utf-8').write(js)
print('p7a_refs.js: %d references, %d bytes' % (len(ref), len(js)))
