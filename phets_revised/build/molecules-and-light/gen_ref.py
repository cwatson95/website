#!/usr/bin/env python3
"""Turn derive.py's refvals.json into two JS part files:

  p2b_fields.js  the fitted valence force constants the JS re-diagonalises
  p7a_ref.js     REF = every reference value selfTest asserts against

Nothing is hand-typed: run derive.py, then this, and the numbers in the sim
are the numbers the Python twin printed.
"""
import io
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
R = json.load(io.open(os.path.join(here, 'refvals.json'), encoding='utf-8'))


def num(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, int):
        return str(v)
    return json.dumps(v)


# ---- p2b_fields.js ----
lines = ["""
/* ================================================================== *
 *  the fitted valence force fields                                    *
 *                                                                     *
 *  GENERATED by build/molecules-and-light/gen_ref.py from derive.py's *
 *  least-squares fit -- do not hand-edit.  Each row is                *
 *  [f_r, f_rr, f_th, f_rth, f_thth, f_thth2] in aJ/A^2 (= mdyn/A),    *
 *  chosen so the mass-weighted Hessian this file builds from them     *
 *  reproduces the MEASURED fundamentals of that molecule.  Where the  *
 *  three measured numbers do not determine the four symmetry          *
 *  constants of a bent XY2, the solution returned is the one of       *
 *  SMALLEST stretch-bend interaction that still fits -- a stated      *
 *  choice, and the reason the A1 mode SHAPES are labelled model.      *
 * ================================================================== */
const FIELDS = {"""]
for k in sorted(R['FIELDS']):
    lines.append('  %s: [%s],' % (k, ', '.join(repr(x) for x in R['FIELDS'][k])))
lines.append('};')
io.open(os.path.join(here, 'p2b_fields.js'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

# ---- p7a_ref.js ----
keys = [k for k in sorted(R) if isinstance(R[k], (int, float, bool)) and not isinstance(R[k], bool)]
out = ["""
/* ================================================================== *
 *  REF -- reference values printed by build/molecules-and-light/      *
 *  derive.py (the Python twin).  GENERATED by gen_ref.py; every       *
 *  assertion tagged (python) or (scipy) in selfTest reads one of      *
 *  these, and none of them was typed by hand.                         *
 * ================================================================== */
const REF = {"""]
for k in sorted(R):
    v = R[k]
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        out.append("  '%s': %s," % (k, num(v)))
out.append('};')
# the arrays and structures selfTest needs
out.append("const REF_MODES = %s;" % json.dumps(
    {k: dict(nu=v['nu'], d=v['d'], sym=v['sym'], distinct=v.get('distinct'))
     for k, v in R['MODES'].items()}, separators=(',', ':')))
out.append("const REF_BENT_B2 = %s;" % json.dumps(R['BENT_B2'], separators=(',', ':')))
out.append("const REF_IRACT = %s;" % json.dumps(R['IRACT'], separators=(',', ':')))
out.append("const REF_PHOTONS = %s;" % json.dumps(R['photons'], separators=(',', ':')))
out.append("const REF_THRESH = %s;" % json.dumps(R['THRESH_NM'], separators=(',', ':')))
out.append("const REF_STAT = %s;" % json.dumps(R['stat'], separators=(',', ':')))
out.append("const REF_RNG_FIRST = %s;" % json.dumps(R['mulberry_first'], separators=(',', ':')))
out.append("const REF_N_STAT = %d;" % R['N_STAT'])
io.open(os.path.join(here, 'p7a_ref.js'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('p2b_fields.js: %d molecules; p7a_ref.js: %d scalar refs'
      % (len(R['FIELDS']), sum(1 for k in R if isinstance(R[k], (int, float)) and not isinstance(R[k], bool))))
